// Writes src/RevenueRecovery/Simulator/SimulatorSeedStats.res: what the seeded counts in
// retry-stats.csv say per cluster (tries, worked, best days and hours), in plain words, for the
// story form's card chain. Run again after changing the seed: node simulator/selfhost/model/seed-summary.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const csv = fs
  .readFileSync(path.join(here, "retry-stats.csv"), "utf8")
  .trim()
  .split("\n")
  .slice(1);
const out = path.join(
  here,
  "../../../src/RevenueRecovery/Simulator/SimulatorSeedStats.res",
);

const DAYS = [
  "Mondays",
  "Tuesdays",
  "Wednesdays",
  "Thursdays",
  "Fridays",
  "Saturdays",
  "Sundays",
];
const ordinal = (n) =>
  `${n}${n % 10 === 1 && n !== 11 ? "st" : n % 10 === 2 && n !== 12 ? "nd" : n % 10 === 3 && n !== 13 ? "rd" : "th"}`;
const hour = (h) =>
  h === 0 || h === 24
    ? "midnight"
    : h === 12
      ? "noon"
      : h < 12
        ? `${h} AM`
        : `${h - 12} PM`;
const pct = (k, n) => Math.round((100 * k) / n);

// The slots with the highest rate (all of them when every slot is the same: no best)
function best(slots) {
  const rates = slots.map(({ n, k }) => (n ? k / n : 0));
  const top = Math.max(...rates);
  const idx = rates.flatMap((r, i) => (Math.abs(r - top) < 1e-9 ? [i] : []));
  return {
    idx,
    k: slots[idx[0]].k,
    n: slots[idx[0]].n,
    flat: idx.length === slots.length,
  };
}
// Runs of consecutive indexes: [[9, 17], ...]
const runs = (idx) =>
  idx.reduce(
    (acc, i) =>
      acc.length && acc.at(-1)[1] === i - 1
        ? ((acc.at(-1)[1] = i), acc)
        : [...acc, [i, i]],
    [],
  );

const rows = csv.map((line) => {
  const [key, json] = [
    line.slice(0, line.indexOf(",")),
    line.slice(line.indexOf(",") + 1),
  ];
  // A CSV field: in double quotes, with inner quotes doubled
  const stats = JSON.parse(json.replace(/^"|"$/g, "").replaceAll('""', '"'));
  const cluster = key.split("|")[1].split("/")[0];
  const tries = stats.dow.reduce((t, s) => t + s.n, 0);
  const worked = stats.dow.reduce((t, s) => t + s.k, 0);
  const dom = best(stats.dom),
    dow = best(stats.dow),
    hod = best(stats.hod);
  const days = dom.flat
    ? "any day of the month"
    : `the ${dom.idx.map((i) => ordinal(i + 1)).join(" and ")}`;
  const weekdays = dow.flat
    ? "any weekday"
    : runs(dow.idx)
        .map(([a, b]) => (a === b ? DAYS[a] : `${DAYS[a]} to ${DAYS[b]}`))
        .join(", ");
  const hours = hod.flat
    ? "any hour"
    : runs(hod.idx)
        .map(([a, b]) => `${hour(a)} to ${hour(b + 1)}`)
        .join(", ");
  return {
    cluster,
    tries,
    worked,
    days,
    daysRate: pct(dom.k, dom.n),
    weekdays,
    weekdaysRate: pct(dow.k, dow.n),
    hours,
    hoursRate: pct(hod.k, hod.n),
  };
});

const str = (s) => JSON.stringify(s);
const res = `// Generated by simulator/selfhost/model/seed-summary.mjs from retry-stats.csv (the seeded counts,
// made up for the demo). Do not edit by hand. Times are UTC, as the engine files them.
type clusterSeed = {
  cluster: string,
  tries: int,
  worked: int,
  days: string,
  daysRate: int,
  weekdays: string,
  weekdaysRate: int,
  hours: string,
  hoursRate: int,
}

let seeds: array<clusterSeed> = [
${rows
  .map(
    (r) => `  {
    cluster: ${str(r.cluster)},
    tries: ${r.tries},
    worked: ${r.worked},
    days: ${str(r.days)},
    daysRate: ${r.daysRate},
    weekdays: ${str(r.weekdays)},
    weekdaysRate: ${r.weekdaysRate},
    hours: ${str(r.hours)},
    hoursRate: ${r.hoursRate},
  },`,
  )
  .join("\n")}
]
`;
fs.writeFileSync(out, res);
console.log(
  `wrote ${path.relative(process.cwd(), out)}: ${rows.map((r) => r.cluster).join(", ")}`,
);
